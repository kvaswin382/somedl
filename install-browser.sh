#!/usr/bin/env bash
set -euo pipefail
if [ "$(id -u)" -ne 0 ]; then echo 'Run: sudo bash /opt/zedair/install-browser.sh'; exit 1; fi
if [ ! -x /opt/zedair/venv/bin/python ]; then echo 'Install Zedair first.'; exit 1; fi
python3 - <<'PY'
import shutil
if shutil.disk_usage('/opt/zedair').free < 1536*1024**2:
    raise SystemExit('Keep at least 1.5 GiB free on the internal drive before installing the optional browser.')
PY
if [ "${1:-}" != '--installed' ]; then
  /opt/zedair/venv/bin/python -m pip install --no-cache-dir 'playwright==1.65.1'
fi
PLAYWRIGHT_BROWSERS_PATH=/opt/zedair/browsers /opt/zedair/venv/bin/python -m playwright install --with-deps --only-shell chromium
chmod -R a+rX /opt/zedair/browsers
# Allow only the installed browser executable to create its sandbox namespaces.
# Keep Ubuntu's global restriction and Chromium's sandbox enabled.
python3 - <<'APPARMOR'
from pathlib import Path
import shutil,subprocess
restriction=Path('/proc/sys/kernel/apparmor_restrict_unprivileged_userns')
if restriction.exists() and restriction.read_text().strip()=='1':
    parser=shutil.which('apparmor_parser')
    if not parser:raise SystemExit('AppArmor parser is missing. Install apparmor-utils, then rerun this installer.')
    root=Path('/opt/zedair/browsers')
    binaries=[p.resolve() for p in root.rglob('*') if p.name in ('chrome-headless-shell','headless_shell','chrome') and p.is_file() and p.resolve().is_relative_to(root)]
    if not binaries:raise SystemExit('Browser executable not found after installation')
    rules='\n'.join('profile zedair-browser-'+str(i)+' "'+str(p)+'" flags=(unconfined) {\n  userns,\n}\n' for i,p in enumerate(sorted(set(binaries))))
    profile=Path('/etc/apparmor.d/zedair-browser')
    profile.write_text('# Zedair installed browser sandbox only; generated by install-browser.sh\n'+rules)
    subprocess.run([parser,'-r',str(profile)],check=True)
APPARMOR
runuser -u zedair -- env PLAYWRIGHT_BROWSERS_PATH=/opt/zedair/browsers /opt/zedair/venv/bin/python - <<'SMOKE'
from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,chromium_sandbox=True,args=['--disable-dev-shm-usage'])
    browser.close()
print('Browser sandbox launch check passed for the zedair account.')
SMOKE
printf '%s\n' 'Optional browser installed for video detection and Facebook profiles.' 'Restart: sudo systemctl restart zedair' 'Enable Browser fallback when adding a download. One browser page runs only after normal extraction fails.'
